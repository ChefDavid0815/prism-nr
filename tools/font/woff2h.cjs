// Turns a WOFF 1.0 font into an sfnt (TTF/OTF) and writes it as a C++ byte array header, so
// Prism Core can embed the app's typeface (JetBrains Mono, SIL OFL 1.1) for its in-game panel.
//   node tools/font/woff2h.cjs <in.woff> <out.h> <symbol>
const fs = require('fs');
const zlib = require('zlib');
const [, , src, out, sym] = process.argv;
const w = fs.readFileSync(src);
if (w.readUInt32BE(0) !== 0x774f4646) throw new Error('not a WOFF 1.0 file');
const flavor = w.readUInt32BE(4), numTables = w.readUInt16BE(12);
const tables = [];
for (let i = 0; i < numTables; ++i) {
  const o = 44 + i * 20;
  const t = { tag: w.readUInt32BE(o), off: w.readUInt32BE(o + 4), comp: w.readUInt32BE(o + 8), orig: w.readUInt32BE(o + 12), sum: w.readUInt32BE(o + 16) };
  const raw = w.subarray(t.off, t.off + t.comp);
  t.data = t.comp < t.orig ? zlib.inflateSync(raw) : raw;
  tables.push(t);
}
tables.sort((a, b) => a.tag - b.tag);
let es = 0; while ((1 << (es + 1)) <= numTables) ++es;
const sr = (1 << es) * 16;
const head = Buffer.alloc(12 + numTables * 16);
head.writeUInt32BE(flavor, 0); head.writeUInt16BE(numTables, 4);
head.writeUInt16BE(sr, 6); head.writeUInt16BE(es, 8); head.writeUInt16BE(numTables * 16 - sr, 10);
let off = head.length; const parts = [head];
tables.forEach((t, i) => {
  const r = 12 + i * 16;
  head.writeUInt32BE(t.tag, r); head.writeUInt32BE(t.sum, r + 4); head.writeUInt32BE(off, r + 8); head.writeUInt32BE(t.orig, r + 12);
  const pad = (4 - (t.orig % 4)) % 4;
  parts.push(t.data, Buffer.alloc(pad)); off += t.orig + pad;
});
const sfnt = Buffer.concat(parts);
const lines = [];
for (let i = 0; i < sfnt.length; i += 24) lines.push('  ' + Array.from(sfnt.subarray(i, i + 24), (b) => b + ',').join(''));
fs.writeFileSync(out, `// Generated by tools/font/woff2h.cjs from ${require('path').basename(src)} (JetBrains Mono, SIL Open Font License 1.1).\n#pragma once\nalignas(4) static const unsigned char ${sym}[${sfnt.length}] = {\n${lines.join('\n')}\n};\n`);
console.log(out, sfnt.length, 'bytes');
